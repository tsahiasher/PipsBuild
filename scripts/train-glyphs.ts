/**
 * Builds src/vision/glyphTemplates.ts from the sample screenshots, labelled by their goldens.
 * Review a new golden (see CLAUDE.md) before training: a misread golden would teach the
 * classifier the same mistake.
 * Each screenshot is used as decoded by Node and by Chrome, plus downscaled copies that
 * simulate small desktop captures. Run: npm run train:glyphs
 */
import { existsSync, writeFileSync } from 'node:fs';
import { browserDecoded, loadImage, samplePath, scaleImage } from './load';
import { normalizeLabelSize, recognize } from '../src/vision/recognize';
import { badgeCell } from '../src/engine/puzzle';
import { classifyGlyph, type GlyphFeatures, type GlyphTemplate } from '../src/vision/glyphs';
import type { RGBAImage } from '../src/vision/image';
import { goldens, parseGolden, type Golden } from '../tests/vision/goldens';

interface Sample {
  puzzle: string;
  ch: string;
  /** Small captures render glyphs differently (blurrier strokes), so they get their own templates. */
  small: boolean;
  g: GlyphFeatures;
}

/** Screenshots of the same puzzle share a key so leave-one-out never trains on the same badges. */
const puzzleKey = (t: Golden) => t.key;

const samples: Sample[] = [];
let mismatches = 0;
for (const t of goldens()) {
  const name = t.name;
  const variants: [string, RGBAImage][] = [['node', loadImage(samplePath(name))]];
  if (existsSync(browserDecoded(name))) {
    const b = loadImage(browserDecoded(name));
    variants.push(['chrome', b]);
    // Simulated small captures, unless the screenshot is already small.
    if (b.width > 700) variants.push(['x0.6', scaleImage(b, 0.6)], ['x0.45', scaleImage(b, 0.45)]);
  }
  const { regions } = parseGolden(t);
  for (const [variant, img] of variants) {
    const res = await recognize(img, { skipClassification: true });
    for (const b of res.badges) {
      const cell = `${b.corner.row - 1},${b.corner.col - 1}`;
      const key = [...regions.entries()].find(([, cells]) => badgeCell({ id: '', color: 0, cells, constraint: null }) === cell)?.[0];
      const label = key ? t.labels[key] : undefined;
      if (!label || [...label].length !== b.glyphs.length) {
        mismatches++;
        console.warn(`${name}/${variant}: badge at ${cell} "${label ?? '?'}" split into ${b.glyphs.length} glyph(s)`);
        continue;
      }
      const small = res.geometry.pitch < 64;
      // Same size normalisation the recogniser applies to small-font (3-character) labels.
      const glyphs = normalizeLabelSize(b.glyphs);
      [...label].forEach((ch, i) => samples.push({ puzzle: puzzleKey(t), ch, small, g: glyphs[i] }));
    }
  }
}

const mean = (list: GlyphFeatures[]): GlyphFeatures => ({
  relW: list.reduce((s, g) => s + g.relW, 0) / list.length,
  relH: list.reduce((s, g) => s + g.relH, 0) / list.length,
  grid: list[0].grid.map((_, i) => list.reduce((s, g) => s + g.grid[i], 0) / list.length),
});

function build(from: Sample[]): GlyphTemplate[] {
  const byCh = new Map<string, GlyphFeatures[]>();
  for (const s of from) {
    if (!byCh.has(s.ch)) byCh.set(s.ch, []);
    byCh.get(s.ch)!.push(s.g);
  }
  return [...byCh.entries()].map(([ch, list]) => ({ ch, ...mean(list) }));
}

// Leave-one-puzzle-out: how well do templates generalise to badges never seen in training?
let errors = 0;
let tested = 0;
for (const key of new Set(samples.map((s) => s.puzzle))) {
  const templates = build(samples.filter((s) => s.puzzle !== key));
  const known = new Set(templates.map((x) => x.ch));
  for (const s of samples.filter((x) => x.puzzle === key && known.has(x.ch))) {
    tested++;
    const r = classifyGlyph(s.g, templates);
    if (r.ch !== s.ch) {
      errors++;
      console.log(`  held-out miss: expected ${s.ch} got ${r.ch} (${s.small ? 'small' : 'large'} capture, w=${s.g.relW.toFixed(2)} h=${s.g.relH.toFixed(2)})`);
    }
  }
}
console.log(`segmentation mismatches: ${mismatches}`);
console.log(`leave-one-puzzle-out: ${tested - errors}/${tested} correct`);

const all = build(samples);
const counts = new Map<string, number>();
for (const s of samples) counts.set(s.ch, (counts.get(s.ch) ?? 0) + 1);
const r = (v: number) => Math.round(v * 1000) / 1000;
const body = all
  .sort((a, b) => a.ch.localeCompare(b.ch))
  .map((t) => `  { ch: ${JSON.stringify(t.ch)}, relW: ${r(t.relW)}, relH: ${r(t.relH)}, grid: [${t.grid.map((v) => Math.round(v * 100) / 100).join(',')}] },`)
  .join('\n');
writeFileSync(
  'src/vision/glyphTemplates.ts',
  `// Generated by scripts/train-glyphs.ts — do not edit by hand.\nimport type { GlyphTemplate } from './glyphs';\n\nexport const GLYPH_TEMPLATES: GlyphTemplate[] = [\n${body}\n];\n`,
);
console.log(`wrote ${all.length} templates from ${samples.length} glyphs:`, [...counts].map(([c, n]) => `${c}×${n}`).join(' '));
